"""Publish curated JSON reports and render documentation from them."""

from __future__ import annotations

import json
import shutil
from pathlib import Path


def _reports(directory: Path) -> list[tuple[str, dict]]:
    return [(path.name, json.loads(path.read_text(encoding="utf-8"))) for path in sorted(directory.glob("*.json"))]


def publish_results(results: Path = Path("eval/results"), final: Path = Path("eval/final")) -> list[Path]:
    final.mkdir(parents=True, exist_ok=True)
    selected: dict[str, Path] = {}
    for prefix, stable in (("baseline_fake_", "baseline_fake.json"), ("improved_fake_", "improved_fake.json"), ("memory_fake_", "memory_fake.json")):
        candidates = sorted(results.glob(prefix + "*.json"))
        if candidates:
            selected[stable] = candidates[-1]
    copied = []
    for name, source in selected.items():
        target = final / name
        shutil.copyfile(source, target)
        copied.append(target)
    return copied


def render_eval(final: Path = Path("eval/final"), output: Path = Path("docs/EVAL.md")) -> Path:
    reports = _reports(final)
    lines = ["# Evaluation", "", "This document is generated by `uv run asterline report`; numbers come only from `eval/final/*.json`.", ""]
    for name, data in reports:
        lines += [f"## {name}", "", f"- provider: `{data.get('provider')}`", f"- config: `{data.get('config')}`", f"- cases: {data.get('cases', len(data.get('case_results', [])))}", "", "| Metric | Value | Applicable |", "|---|---:|---:|"]
        for metric, value in data.get("overall", {}).items():
            if isinstance(value, dict) and "value" in value:
                lines.append(f"| {metric} | {value['value']:.4f} | {value.get('applicable', 0)}/{value.get('total', 0)} |")
        lines += ["", "### Per category", "", "| Category | Metric | Value |", "|---|---|---:|"]
        for category, metrics in sorted(data.get("by_category", {}).items()):
            for metric, value in metrics.items():
                if isinstance(value, dict) and "value" in value:
                    lines.append(f"| {category} | {metric} | {value['value']:.4f} |")
        lines += ["", "### Representative failures", ""]
        for failure in data.get("failures", [])[:10]:
            lines.append(f"- `{failure.get('id')}`: {', '.join(failure.get('failed', [])) or failure.get('reason', 'failure')}")
        lines.append("")
    if not reports:
        lines.append("No curated reports have been published yet.")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines), encoding="utf-8")
    return output
