"""Publish curated JSON reports and render documentation from them."""

from __future__ import annotations

import json
import shutil
from pathlib import Path


def _reports(directory: Path) -> list[tuple[str, dict]]:
    return [(path.name, json.loads(path.read_text(encoding="utf-8"))) for path in sorted(directory.glob("*.json"))]


def _dataset_size(path: Path) -> int | None:
    if not path.exists():
        return None
    return sum(1 for line in path.read_text(encoding="utf-8").splitlines() if line.strip())


def publish_results(results: Path = Path("eval/results"), final: Path = Path("eval/final")) -> list[Path]:
    final.mkdir(parents=True, exist_ok=True)
    expected_research_cases = _dataset_size(results.parent / "datasets" / "research.jsonl")
    expected_memory_scenarios = _dataset_size(results.parent / "datasets" / "memory.jsonl")
    selected: dict[str, Path] = {}
    for prefix, stable in (
        ("baseline_fake_", "baseline_fake.json"),
        ("improved_fake_", "improved_fake.json"),
        ("baseline_gemini_", "baseline_gemini.json"),
        ("baseline_ollama_", "baseline_ollama.json"),
        ("improved_ollama_", "improved_ollama.json"),
        ("memory_fake_", "memory_fake.json"),
    ):
        candidates = []
        for candidate in sorted(results.glob(prefix + "*.json")):
            try:
                report = json.loads(candidate.read_text(encoding="utf-8"))
            except (OSError, json.JSONDecodeError):
                continue
            if report.get("status") != "complete":
                continue
            if prefix == "memory_fake_" and expected_memory_scenarios is not None:
                if len(report.get("scenarios", [])) != expected_memory_scenarios:
                    continue
            elif prefix != "memory_fake_" and expected_research_cases is not None:
                if report.get("cases") != expected_research_cases:
                    continue
            candidates.append(candidate)
        if candidates:
            selected[stable] = candidates[-1]
    copied = []
    for name, source in selected.items():
        target = final / name
        shutil.copyfile(source, target)
        copied.append(target)
    return copied


def render_eval(final: Path = Path("eval/final"), output: Path = Path("docs/EVAL.md")) -> Path:
    reports = _reports(final)
    lines = ["# Evaluation", "", "This document is generated by `uv run asterline report`; numbers come only from `eval/final/*.json`.", "", "FakeLLM results validate offline plumbing and deterministic checks; they are not estimates of Gemini or Ollama answer quality. Real-provider results apply only to their named provider/model and show applicable denominators; provider errors are not answer-quality successes.", ""]
    indexed = dict(reports)
    comparison_rows: list[str] = []
    for provider in ("fake", "ollama", "gemini"):
        baseline = indexed.get(f"baseline_{provider}.json")
        improved = indexed.get(f"improved_{provider}.json")
        if not baseline or not improved:
            continue
        if baseline.get("status") != "complete" or improved.get("status") != "complete":
            continue
        if baseline.get("provider") != improved.get("provider") or baseline.get("model") != improved.get("model"):
            continue
        for category in sorted(set(baseline.get("by_category", {})) & set(improved.get("by_category", {}))):
            before_metrics = baseline["by_category"][category]
            after_metrics = improved["by_category"][category]
            for metric in ("fact_accuracy", "citation_validity", "citation_precision", "citation_recall", "abstention_accuracy", "conflict_handling"):
                before = before_metrics.get(metric)
                after = after_metrics.get(metric)
                if not isinstance(before, dict) or not isinstance(after, dict) or "value" not in before or "value" not in after:
                    continue
                delta = (after["value"] - before["value"]) * 100
                comparison_rows.append(
                    f"| {provider}/{baseline.get('model', 'unknown')} | {category} | {metric} | {before['value']:.4f} ({before.get('applicable', 0)}) | {after['value']:.4f} ({after.get('applicable', 0)}) | {delta:+.2f} pp |"
                )
    if comparison_rows:
        lines += [
            "## Paired baseline vs improved comparisons",
            "",
            "Only complete reports with the same named provider and model are compared. Values include applicable-case counts; deltas are percentage points.",
            "",
            "| Provider/model | Category | Metric | Baseline (n) | Improved (n) | Delta |",
            "|---|---|---|---:|---:|---:|",
            *comparison_rows,
            "",
        ]
    for name, data in reports:
        scenarios = data.get("scenarios", [])
        case_results = data.get("case_results", [])
        lines += [f"## {name}", "", f"- provider: `{data.get('provider', 'unknown')}`"]
        if data.get("model"):
            lines.append(f"- model: `{data['model']}`")
        if "no_fallback" in data:
            lines.append(f"- fallback disabled: `{str(bool(data['no_fallback'])).lower()}`")
        if scenarios:
            passed = sum(bool(scenario.get("passed")) for scenario in scenarios)
            lines += ["- workflow: `memory scenarios`", f"- scenarios: {len(scenarios)}", f"- passed: {passed}/{len(scenarios)}"]
        else:
            lines += [f"- config: `{data.get('config', 'unknown')}`", f"- cases: {data.get('cases', len(case_results))}"]
        lines += ["", "| Metric | Value | Applicable / basis |", "|---|---:|---:|"]
        overall = data.get("overall", {})
        if overall:
            for metric, value in overall.items():
                if isinstance(value, dict) and "value" in value:
                    lines.append(f"| {metric} | {value['value']:.4f} | {value.get('applicable', 0)}/{value.get('total', 0)} |")
                elif isinstance(value, (int, float)):
                    basis = "count" if metric.endswith("_count") else ("per question" if metric == "llm_calls_per_question" else "aggregate")
                    lines.append(f"| {metric} | {value:.4f} | {basis} |")
        else:
            for metric in ("memory_write_precision", "memory_write_recall", "forget_success", "isolation_leakage", "secret_leak_count", "sensitive_stored_count"):
                value = data.get(metric)
                if isinstance(value, (int, float)):
                    lines.append(f"| {metric} | {value:.4f} | aggregate over {len(scenarios)} scenarios |")
        lines += ["", "### Per category", ""]
        if scenarios:
            counts: dict[str, list[int]] = {}
            for scenario in scenarios:
                category = str(scenario.get("category", "unknown"))
                counts.setdefault(category, [0, 0])
                counts[category][1] += 1
                counts[category][0] += int(bool(scenario.get("passed")))
            lines += ["| Category | Pass rate | Passed / total |", "|---|---:|---:|"]
            for category, (category_passed, total) in sorted(counts.items()):
                lines.append(f"| {category} | {category_passed / total:.4f} | {category_passed}/{total} |")
        else:
            lines += ["| Category | Metric | Value |", "|---|---|---:|"]
            for category, metrics in sorted(data.get("by_category", {}).items()):
                for metric, value in metrics.items():
                    if isinstance(value, dict) and "value" in value:
                        lines.append(f"| {category} | {metric} | {value['value']:.4f} |")
        lines += ["", "### Representative failures", ""]
        failures = data.get("failures", [])
        if scenarios:
            failures = [scenario for scenario in scenarios if not scenario.get("passed")]
        for failure in failures[:10]:
            failed_checks = failure.get("failed", [])
            reason = ", ".join(failed_checks) or failure.get("reason", "scenario failed")
            lines.append(f"- `{failure.get('id')}`: {reason}")
        if not failures:
            lines.append("- None in this report.")
        lines.append("")
    if not reports:
        lines.append("No curated reports have been published yet.")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines), encoding="utf-8")
    return output
